import { useState } from "react";
import { downloadFile } from "../lib/engine";
import { platform, type Analysis, type Incident } from "../lib/platform";
import "./case-comparator.css";

type CaseView = {
  id: string;
  title: string;
  asOf: number;
  status: string;
  leading: { name: string; score: number; confidence: string };
  detectedAt: number | null;
  alarms: number;
  conditions: number;
  clusters: number;
  repeats: number;
  trustworthyChannels: number;
  inspectedChannels: number;
  nextMeasurements: string[];
  recovery: { lastRecoverableStart: number | null; modelTrip: number | null } | null;
};

function snapshot(incident: Incident, asOf: number): Analysis | undefined {
  if (asOf === 240) return incident;
  return incident.snapshots.find((item) => item.time === asOf);
}

/** Compare only evidence available at the requested timestamp. */
function viewFor(incident: Incident, asOf: number): CaseView | null {
  const analysis = snapshot(incident, asOf);
  if (!analysis) return null;
  const d = analysis.diagnosis;
  const a = analysis.alarms;
  const channels = Object.values(d.health);
  return {
    id: incident.id,
    title: incident.title,
    asOf,
    status: d.status,
    leading: {
      name: d.candidates[0].name,
      score: d.candidates[0].score,
      confidence: d.candidates[0].confidence,
    },
    detectedAt: d.firstDetection,
    alarms: a.eventCount,
    conditions: a.uniqueConditions,
    clusters: a.clusters.length,
    repeats: a.reannunciations,
    trustworthyChannels: channels.filter((item) => item.usable).length,
    inspectedChannels: channels.length,
    nextMeasurements: d.nextMeasurements.slice(0, 2).map((item) => item.tag),
    recovery:
      asOf === 240
        ? {
            lastRecoverableStart:
              incident.recovery.actions
                .map((action) => action.latest)
                .filter((value): value is number => value !== null)
                .reduce<number | null>((max, value) => (max === null ? value : Math.max(max, value)), null),
            modelTrip: incident.recovery.base.trip,
          }
        : null,
  };
}

export function CaseComparator({
  reference,
  time,
  onOpenCase,
}: {
  reference: Incident;
  time: number;
  onOpenCase: (id: string) => void;
}) {
  const [chosenId, setChosenId] = useState(
    () => platform.cases.find((item) => item.id !== reference.id)?.id ?? reference.id,
  );
  const other =
    platform.cases.find((item) => item.id === chosenId && item.id !== reference.id) ??
    platform.cases.find((item) => item.id !== reference.id);
  const first = viewFor(reference, time);
  const second = other ? viewFor(other, time) : null;

  if (!first || !second || !other) {
    return (
      <div className="p-prefix-notice" role="status">
        Two complete sessions at +{time}s are needed for comparison.
      </div>
    );
  }

  function exportComparison() {
    if (!first || !second) return;
    const report = {
      schemaVersion: 1,
      kind: "time-bounded-simulator-case-comparison",
      model: platform.model,
      asOfSeconds: time,
      left: first,
      right: second,
      limitations: [
        "Both cases are generated by the same reduced-order simulator; this is not an independent benchmark.",
        "Evidence scores are rule-based support, not calibrated probabilities.",
        "Only observations through the selected time are compared. Recovery is withheld until +240s.",
        "Recovery results are conditional 240-second simulations, never live plant actuation instructions.",
      ],
    };
    downloadFile(
      `triplens-${first.id}-vs-${second.id}-t${time}.json`,
      JSON.stringify(report, null, 2),
    );
  }

  const rows: { title: string; value: (c: CaseView) => string }[] = [
    { title: "Leading hypothesis", value: (c) => c.status === "nominal" ? "No confirmed deviation" : c.leading.name },
    { title: "Evidence support", value: (c) => `${c.leading.score}/100 (${c.leading.confidence})` },
    { title: "First detection", value: (c) => c.detectedAt === null ? "None" : `+${c.detectedAt}s` },
    { title: "Alarm events", value: (c) => c.alarms.toLocaleString() },
    { title: "Distinct conditions", value: (c) => String(c.conditions) },
    { title: "Process clusters", value: (c) => String(c.clusters) },
    { title: "Repeated announcements", value: (c) => String(c.repeats) },
    { title: "Usable evidence channels", value: (c) => `${c.trustworthyChannels}/${c.inspectedChannels}` },
    { title: "Next checks", value: (c) => c.nextMeasurements.join(", ") || "None" },
  ];
  if (time === 240) {
    rows.push(
      {
        title: "Predicted unmitigated trip",
        value: (c) => c.recovery?.modelTrip === null || !c.recovery
          ? "No trip in 240s model" : `+${c.recovery.modelTrip}s`,
      },
      {
        title: "Latest modeled recoverable start",
        value: (c) => c.recovery?.lastRecoverableStart === null || !c.recovery
          ? "None" : `+${c.recovery.lastRecoverableStart}s`,
      },
    );
  }

  return (
    <section className="case-compare" aria-label="Time-bounded comparison of simulated incidents">
      <div className="case-compare-header">
        <div>
          <span className="eyebrow text-mint">EVIDENCE / SIDE BY SIDE</span>
          <h2>Compare incidents at the same moment.</h2>
          <p>Two different simulated faults; one observation cutoff. No scenario labels enter diagnosis.</p>
        </div>
        <button type="button" onClick={exportComparison}>Export comparison JSON ↓</button>
      </div>
      <div className="case-compare-cards">
        <div className="case-compare-card">
          <span className="case-compare-overline">CURRENT SESSION</span>
          <strong>{first.id} / {first.title}</strong>
          <small>Observed through +{time}s</small>
          <button type="button" onClick={() => onOpenCase(first.id)}>Open evidence ↗</button>
        </div>
        <div className="case-compare-card">
          <label className="case-compare-overline" htmlFor="comparison-case">COMPARE AGAINST</label>
          <select
            id="comparison-case"
            value={other.id}
            onChange={(event) => setChosenId(event.target.value)}
          >
            {platform.cases.filter((item) => item.id !== reference.id).map((item) => (
              <option key={item.id} value={item.id}>{item.id} / {item.title}</option>
            ))}
          </select>
          <small>Observed through +{time}s</small>
          <button type="button" onClick={() => onOpenCase(other.id)}>Open evidence ↗</button>
        </div>
      </div>
      <div className="case-compare-tablewrap">
        <table className="case-compare-table">
          <caption>Time-matched, observed-data summaries (not ground-truth labels)</caption>
          <thead><tr><th scope="col">MEASURE</th><th scope="col">{first.id}</th><th scope="col">{second.id}</th></tr></thead>
          <tbody>
            {rows.map((row) => (
              <tr key={row.title}>
                <th scope="row">{row.title}</th>
                <td>{row.value(first)}</td>
                <td>{row.value(second)}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      <p className="case-compare-limit">
        SIMULATOR ONLY · Rule-based scores are not probabilities. These cases share one simulator,
        not an independent reference dataset. Recovery appears only at +240s, and modeled
        threshold avoidance does not imply real-world safety.
      </p>
    </section>
  );
}
